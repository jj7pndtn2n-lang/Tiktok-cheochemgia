-- Server-authoritative replenishment: clients may request a check every 5 seconds.
-- The transaction lock prevents simultaneous clients from overfilling the shared map.
create or replace function public.replenish_game_knives()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_count integer;
  added integer := 0;
  i integer;
begin
  perform pg_advisory_xact_lock(hashtext('moon_hunt_game_knives_replenish'));
  select count(*) into current_count from public.game_knives;
  if current_count < 100 then
    added := greatest(0, 300 - current_count);
    for i in 1..added loop
      insert into public.game_knives(x,y)
      values(80 + random()*7040, 80 + random()*4640);
    end loop;
    current_count := current_count + added;
  end if;
  return jsonb_build_object('ok',true,'count',current_count,'added',added);
end;
$$;
revoke all on function public.replenish_game_knives() from public;
grant execute on function public.replenish_game_knives() to anon, authenticated;

create or replace function public.admin_game_command(command_text text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  cmd text := lower(trim(command_text));
  n integer;
  i integer;
  bot_names text[] := array['Minh Anh','Gia Huy','Bảo Ngọc','Tuấn Kiệt','Khánh Linh','Đức Anh','Phương Thảo','Hoàng Nam','Thảo Vy','Quốc Bảo','Hải Yến','Nhật Minh','Thanh Trúc','Duy Khang','Ngọc Mai','Anh Khoa','Kim Ngân','Trọng Nhân','Thiên An','Quỳnh Chi'];
  bx double precision;
  by double precision;
  new_epoch bigint;
  current_count integer;
begin
  if auth.uid() is null or not exists(select 1 from public.game_admins a where a.user_id=auth.uid()) then
    return jsonb_build_object('ok',false,'message','Bạn không có quyền Admin. Hãy đăng nhập bằng email đã được cấp quyền.');
  end if;

  if cmd ~ '^/bot[[:space:]]+add[[:space:]]+[0-9]+$' then
    n := split_part(cmd,' ',3)::integer;
    if n < 1 or n > 50 then return jsonb_build_object('ok',false,'message','Số bot hợp lệ: 1–50.'); end if;
    for i in 1..n loop
      bx := 100 + random()*7000; by := 100 + random()*4600;
      insert into public.game_players(id,nickname,x,y,power,score,alive,updated_at,is_bot,bot_seed,bot_origin_x,bot_origin_y,created_at)
      values('bot-'||gen_random_uuid()::text, bot_names[1+floor(random()*array_length(bot_names,1))::int], bx,by,1,1,true,now(),true,floor(random()*2147483000)::int,bx,by,now());
    end loop;
    return jsonb_build_object('ok',true,'action','bot_add','message','Đã triệu hồi '||n||' bot.');
  elsif cmd ~ '^/sickle[[:space:]]+add[[:space:]]+[0-9]+$' then
    n := split_part(cmd,' ',3)::integer;
    if n < 1 then return jsonb_build_object('ok',false,'message','Số lưỡi liềm phải lớn hơn 0.'); end if;
    perform pg_advisory_xact_lock(hashtext('moon_hunt_game_knives_replenish'));
    select count(*) into current_count from public.game_knives;
    n := least(n, greatest(0, 300-current_count));
    if n < 1 then return jsonb_build_object('ok',false,'message','Bản đồ đã đủ 300 lưỡi liềm.'); end if;
    for i in 1..n loop
      insert into public.game_knives(x,y) values(80+random()*7040,80+random()*4640);
    end loop;
    return jsonb_build_object('ok',true,'action','sickle_add','message','Đã thêm '||n||' lưỡi liềm (giới hạn tối đa 300).');
  elsif cmd = '/reset' then
    delete from public.game_players;
    delete from public.game_knives;
    for i in 1..300 loop
      insert into public.game_knives(x,y) values(80+random()*7040,80+random()*4640);
    end loop;
    update public.game_settings set reset_epoch=reset_epoch+1,updated_at=now() where id=1 returning reset_epoch into new_epoch;
    return jsonb_build_object('ok',true,'action','reset','message','Đã reset bản đồ. Tất cả người chơi sẽ bắt đầu lại từ đầu.','reset_epoch',new_epoch);
  else
    return jsonb_build_object('ok',false,'message','Lệnh chưa hợp lệ. Dùng /bot add 10, /sickle add 50 hoặc /reset.');
  end if;
end $$;
revoke all on function public.admin_game_command(text) from public;
grant execute on function public.admin_game_command(text) to authenticated;

