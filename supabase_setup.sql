create extension if not exists pgcrypto;

create table if not exists public.game_chat (
  id bigint generated by default as identity primary key,
  sender_id text not null,
  nickname text not null default 'Thợ săn',
  message text not null check (char_length(message) between 1 and 240),
  created_at timestamptz not null default now()
);
create index if not exists game_chat_created_idx on public.game_chat(id desc);
alter table public.game_chat enable row level security;
drop policy if exists "chat messages readable by everyone" on public.game_chat;
create policy "chat messages readable by everyone" on public.game_chat for select to anon, authenticated using (true);
drop policy if exists "chat messages insertable by everyone" on public.game_chat;
create policy "chat messages insertable by everyone" on public.game_chat for insert to anon, authenticated with check (char_length(message) between 1 and 240 and char_length(nickname) between 1 and 18);

do $$ begin
  if to_regclass('public.game_players') is null then
    create table public.game_players (
      id text primary key, nickname text not null default 'Thợ săn', x double precision not null default 3600,
      y double precision not null default 2400, power integer not null default 1, score integer not null default 1,
      alive boolean not null default true, updated_at timestamptz not null default now()
    );
  end if;
end $$;
alter table public.game_players add column if not exists is_bot boolean not null default false;
alter table public.game_players add column if not exists bot_seed integer;
alter table public.game_players add column if not exists bot_origin_x double precision;
alter table public.game_players add column if not exists bot_origin_y double precision;
alter table public.game_players add column if not exists created_at timestamptz not null default now();
alter table public.game_players add column if not exists character_index integer not null default 0;

-- Existing game_knives is retained. Create it only if it doesn't exist yet.
do $$ begin
  if to_regclass('public.game_knives') is null then
    create table public.game_knives (id uuid primary key default gen_random_uuid(), x double precision not null, y double precision not null, created_at timestamptz not null default now());
  end if;
end $$;

create table if not exists public.game_settings (
  id integer primary key check (id=1), reset_epoch bigint not null default 0, updated_at timestamptz not null default now()
);
insert into public.game_settings(id,reset_epoch) values(1,0) on conflict(id) do nothing;
alter table public.game_settings enable row level security;
drop policy if exists "game settings readable by everyone" on public.game_settings;
create policy "game settings readable by everyone" on public.game_settings for select to anon, authenticated using (true);

create table if not exists public.game_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.game_admins enable row level security;
drop policy if exists "admins can read their own admin row" on public.game_admins;
create policy "admins can read their own admin row" on public.game_admins for select to authenticated using (user_id = auth.uid());

